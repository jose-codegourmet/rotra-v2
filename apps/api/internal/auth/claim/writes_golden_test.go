// The successful claim of a club record's link against what the real Route Handler and @rotra/db did
// (apps/api/testdata/tools/capture-writes-player.test.mjs, group claim; cases generated by gen-writes-player-cases.py, next to
// the Player's own writes, which share the seed). Only the Supabase calls are replaced in the capture, so the session cookies
// are Go's own and are asserted in post_success_test.go. The cases pin the RTR ID allocated by the record's shared entry email
// and the registering email, and the join of the entry's records (claimSharedEntry).
func TestClaimWritesGolden(t *testing.T) {
	writetest.ReplayFull(t, "../../playerwrites/testdata", "claim", func(pool *pgxpool.Pool, svc *session.Service, st *store.Store, log *slog.Logger, now func() time.Time) func(*http.ServeMux) {
		routes, err := claim.Register(claim.Deps{Pool: pool, Service: svc, Store: st, ReadLimiter: httpapi.NewRateLimiter(1_000_000, nil), Clock: now, Logger: log})
		if err != nil {
			panic(err)
		}
		return routes
	})
}
