// The cases the TypeScript was captured with (apps/api/testdata/tools/capture-writes-player.test.mjs, group google; the cases are
// generated by gen-writes-player-cases.py): the seven Google routes, with what the TypeScript decides before it needs the provider.
// There is no Google and no Supabase in the capture, so the trip to Google, the held account and everything decided after them are
// pinned by the other tests of this package, against a fake Google, and by TestGoldenAfterGoogle (the group googleflow), which
// compares them with the TypeScript with the held state stubbed. The redirect's origin and the cookies are Go's own and are
// ignored by the cases that name them.
func TestGolden(t *testing.T) {
	writetest.ReplayFull(t, "../../playerwrites/testdata", "google", func(pool *pgxpool.Pool, svc *session.Service, st *store.Store, log *slog.Logger, now func() time.Time) func(*http.ServeMux) {
		_, key, _ := ed25519.GenerateKey(rand.Reader)
		g, err := google.New(google.Deps{Pool: pool, Service: svc, Store: st, Sealer: google.NewSealer(key), RedirectBase: "https://player.test", Clock: now, Logger: log})
		if err != nil {
			panic(err)
		}
		registration, err := register.RegisterGoogle(register.Deps{Pool: pool, Service: svc, Store: st, Logger: log, Clock: now}, g)
		if err != nil {
			panic(err)
		}
		routes := g.Routes()
		return func(mux *http.ServeMux) { routes(mux); registration(mux) }
	})
}
